final List<PuzzleDef> allPuzzles = [for (final room in rooms) ...room.puzzles];

RoomDef roomForPuzzle(PuzzleDef puzzle) {
  return rooms.firstWhere(
    (room) => room.puzzles.any((candidate) => candidate.id == puzzle.id),
  );
}

PuzzleDef? puzzleById(String id) {
  for (final puzzle in allPuzzles) {
    if (puzzle.id == id) return puzzle;
  }
  return null;
}
